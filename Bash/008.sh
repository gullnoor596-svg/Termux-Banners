# ===== $rm -R ASCII (GREEN) =====
show_rm() {
echo -e "\e[32m"   # green color
cat << 'EOF'

             ,----------------,              ,---------,
        ,-----------------------,          ,"        ,"|
      ,"                      ,"|        ,"        ,"  |
     +-----------------------+  |      ,"        ,"    |
     |  .-----------------.  |  |     +---------+      |
     |  |                 |  |  |     | -==----'|      |
     |  |  $rm -R         |  |  |     |         |      |
     |  |                 |  |  |/----|`---=    |      |
     |  |                 |  |  |   ,/|==== ooo |      ;
     |  `-----------------'  |," .;'| |(((( [33]|    ,"
     +-----------------------+  ;;  | |         |,"     
        /_)______________(_/  //'   | +---------+
   ___________________________/___  `,
  /  oooooooooooooooo  .o.  oooo /,   \,"-----------
 / ==ooooooooooooooo==.o.  ooo= //   ,`\--{)B     ,"
/_==__==========__==_ooo__ooo=_/'   /___________,"
`-----------------------------'

EOF
echo -e "\e[0m"
}

# Start par show
show_rm

# clear override
clear() {
  command clear
  show_rm
}

# CTRL + L override
bind -x '"\C-l": clear'             
